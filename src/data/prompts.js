export function getPromptPool(categoryKey) {
  if (categoryKey === "random") {
    return PROMPT_CATEGORIES.flatMap((c) => c.prompts);
  }
  const category = PROMPT_CATEGORIES.find((c) => c.key === categoryKey);
  return category ? category.prompts : [];
}

export function getCategoryMeta(categoryKey) {
  if (categoryKey === "random") {
    return { key: "random", label: "Random", icon: "fa-regular fa-shuffle", description: "A prompt from anywhere." };
  }
  return PROMPT_CATEGORIES.find((c) => c.key === categoryKey) || null;
}

export function pickRandomPrompt(categoryKey, excluding) {
  const pool = getPromptPool(categoryKey);
  if (pool.length === 0) return null;
  if (pool.length === 1) return pool[0];
  let choice = excluding;
  while (choice === excluding) {
    choice = pool[Math.floor(Math.random() * pool.length)];
  }
  return choice;
}
